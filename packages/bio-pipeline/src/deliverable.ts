/** Version of the raw -> effective-input transform shared by the TS materializer and prepare_data.py. */
export const preparationPolicy = "omerta-bio-effective-input-v1";
/** Software-owned preparation step exported with every deliverable. Never model-written. */
export const prepareScript: string = readFileSync(new URL("./prepare_data.py", import.meta.url), "utf8");
export const preparedDirectory = "derived";

/** Static, data-free description of the analysis inputs, for the code-phase prompt. */
export const layoutContract = "Input layout contract (software-owned): BIO_DATA_DIR holds one file per declared dataset with the same file name and format, plus manifest.json. " +
  "Every CSV/TSV file is a row table: header line first, then one row per effective unit in software unit order, no index column, cells keep their original text (missing markers unchanged); a cell is quoted only if it contains the delimiter, a quote or a newline. " +
  "Row-axis sources keep their columns. Column-axis (feature-by-sample) sources are transposed: the first column is the unit ID column, named after the source's first header, followed by one column per feature named by the source's leading annotation column; other annotation columns are dropped. " +
  "JSON sources are arrays of records with sorted keys. The exported deliverable recreates exactly these bytes from the raw data with a software preparation step before it runs your code, so never read raw or host paths and never reconstruct the raw layout. Field lists per file are in worker-context.json input.schemas.";

export interface PreparationSpecFile {
  file: string; format: "csv" | "tsv" | "json"; sampleAxis: "rows" | "columns"; idField: string; featureFields?: string[];
  rawSha256: string; rawBytes: number; keep: string[]; sha256: string; bytes: number;
}

const sha256 = (bytes: string | Uint8Array) => createHash("sha256").update(bytes).digest("hex");

/** Deterministic spec from the journaled gate decision and the materialized receipt. */
export function preparationSpec(input: EffectiveInput): string {
  if (!input.layouts) throw new Error("effective input has no layout receipt; deliverable preparation unavailable (start a new investigation)");
  const manifestText = readFileSync(path.join(input.directory, "manifest.json"), "utf8");
  if (sha256(manifestText) !== input.manifestHash) throw new Error("effective input manifest changed");
  const manifest = JSON.parse(manifestText) as DatasetManifest;
  if (input.layouts.length !== input.schemas.length || input.layouts.length !== manifest.files.length) throw new Error("effective input layout coverage mismatch");
  const files: PreparationSpecFile[] = input.layouts.map(layout => {
    const schema = input.schemas.find(s => s.file === layout.file), entry = manifest.files.find(f => f.path === layout.file);
    if (!schema || !entry || !schema.representatives.length) throw new Error("effective input layout coverage mismatch");
    return { file: layout.file, format: layout.format, sampleAxis: layout.sampleAxis, idField: layout.idField,
      ...(layout.sampleAxis === "columns" ? { featureFields: layout.featureFields ?? [layout.idField] } : {}),
      rawSha256: layout.rawSha256, rawBytes: layout.rawBytes, keep: [...schema.representatives], sha256: entry.sha256, bytes: entry.bytes };
  });
  return canonicalJson({ version: 1, policy: preparationPolicy, files, manifest: manifestText, manifestSha256: input.manifestHash });
}

function analysisCommand(runtime: AnalysisRuntime): string[] {
  const name = `code/${codeName(runtime)}`;
  return runtime === "python" ? ["python", "-I", "-B", name] : runtime === "r" ? ["Rscript", "--vanilla", name] : ["node", name];
}

/** The host-written wrapper: verify the software files, prepare from raw ./data, run frozen code. */
export function runAllScript(input: { runtime: AnalysisRuntime; code: string; spec: string; outputs: string[] }): string {
  const expected = { [`code/${codeName(input.runtime)}`]: sha256(input.code), "prepare/prepare_data.py": sha256(prepareScript), "prepare/spec.json": sha256(input.spec) };
  return `#!/usr/bin/env bash
# Generated by Omerta Bio software, not by the AI analyst. Recreates the exact analysed
# inputs from the raw ./data (kept units and layout journaled by the validity gate), then
# runs the frozen analysis on them. Any changed file or raw input stops the run.
set -euo pipefail
source ./env.sh
python -I -B - <<'OMERTA_BIO_VERIFY'
import hashlib
import os
import stat
import sys
expected = ${JSON.stringify(Object.fromEntries(Object.entries(expected).sort(([a], [b]) => a < b ? -1 : 1)), null, 4)}
for name in sorted(expected):
    components = name.split("/")
    if any(os.path.islink("/".join(components[:i + 1])) for i in range(len(components))):
        sys.exit("deliverable linked file refused")
    info = os.lstat(name)
    if not stat.S_ISREG(info.st_mode) or info.st_nlink != 1:
        sys.exit("deliverable non-regular file refused")
    with open(name, "rb") as handle:
        if hashlib.sha256(handle.read()).hexdigest() != expected[name]:
            sys.exit("deliverable integrity check failed: " + name)
OMERTA_BIO_VERIFY
rm -rf ./${preparedDirectory}
python -I -B prepare/prepare_data.py --spec prepare/spec.json --data data --out ${preparedDirectory}
mkdir -p outputs
export BIO_DATA_DIR="$PWD/${preparedDirectory}" BIO_OUTPUT_DIR="$PWD/outputs"
python -I -B - <<'OMERTA_BIO_ANALYSE'
import json
import os
import subprocess
import sys
# A read-only mode bit is not containment: the analyst owns its files and could chmod
# them. Seatbelt denies modification for the whole analysis process tree, including
# transient edits restored before an after-run hash check. The grader supplies its
# full confinement policy here because macOS Seatbelt cannot be nested. This exported host-prepared deliverable requires macOS Seatbelt.
outer = os.environ.get('BIO_ANALYSIS_SANDBOX_PROFILE')
profile = open(outer).read() if outer else '(version 1)(allow default)'
profile += '(deny network*)'
for name in ('derived', 'data', 'prepare', 'code', 'run_all.sh', 'env.sh'):
    profile += '(deny file-write* (subpath ' + json.dumps(os.path.realpath(name)) + '))'
profile += '(deny file-read* (subpath ' + json.dumps(os.path.realpath('data')) + '))'
sys.exit(subprocess.run(['/usr/bin/sandbox-exec', '-p', profile] + ${JSON.stringify(analysisCommand(input.runtime))}).returncode)
OMERTA_BIO_ANALYSE
${input.outputs.includes("results.json") ? "cp outputs/results.json results.json\n" : ""}`;
}
