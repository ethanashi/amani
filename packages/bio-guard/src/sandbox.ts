import { lstatSync, mkdtempSync, readdirSync, rmSync } from "node:fs";
import path from "node:path";
import { HostSandbox, machOLibraryRoots, type SandboxInvocation, type SandboxRequest } from "../../bio-core/src/index.ts";
import { canonicalPath, directory, rejectFirmlinkAlias, within } from "./files.ts";
import { assertVerifiedManifest } from "./manifest.ts";
import { verifyEnvironment, type EnvironmentVerificationCache } from "./environment-cache.ts";
import { assertNoExtendedAcl } from "./acl.ts";

export interface InvestigationLayout {
  root: string;
  data: string;
  sealed: string;
  work: string;
  results: string;
  report: string;
}

export function investigationLayout(root: string): InvestigationLayout {
  if (!path.isAbsolute(root)) throw new Error("investigation root must be absolute");
  rejectFirmlinkAlias(root);
  root = path.resolve(root);
  return { root, data: path.join(root, "data"), sealed: path.join(root, "sealed"), work: path.join(root, "work"),
    results: path.join(root, "results"), report: path.join(root, "report") };
}

export interface AgentSandboxPolicy {
  /** Absolute paths/globs: apply to both the tool permissions AND the OS sandbox. */
  denyReadPaths: string[];
  readableRoots: string[];
  writableRoots: string[];
  failIfUnavailable: true;
  allowUnsandboxedCommands: false;
}

const secrets = [".ssh", ".aws", ".codex", ".gnupg", ".config/gh", ".docker", ".kube",
  ".netrc", ".npmrc", ".git-credentials", ".pypirc"];

function secretReadRoots(home: string): string[] {
  const roots = [...secrets, ...readdirSync(home).filter(name => name.startsWith(".") && ![".local", ".cache", ".cargo", ".rustup", ".pixi", ".bun", ".nvm"].includes(name))].map(entry => path.join(home, entry));
  const resolved: string[] = [];
  for (const root of roots) {
    // Missing credentials are still denied prospectively. Broken links and other
    // lookup failures are refusals, since their actual target cannot be checked.
    try { lstatSync(root); }
    catch (error) { if ((error as NodeJS.ErrnoException).code === "ENOENT") continue; throw error; }
    resolved.push(canonicalPath(root));
  }
  return [...new Set([...roots, ...resolved])];
}

function checkedLayout(layout: InvestigationLayout): InvestigationLayout {
  const root = directory(layout.root);
  const checked = investigationLayout(root);
  for (const name of ["data", "sealed", "work", "results", "report"] as const) {
    if (directory(layout[name]) !== checked[name]) throw new Error(`layout ${name} must be a separate, non-aliased child of the investigation`);
  }
  return checked;
}

export function buildAgentSandboxPolicy(layout: InvestigationLayout, home: string): AgentSandboxPolicy {
  const checked = checkedLayout(layout);
  const realHome = directory(home);
  const secretRoots = secretReadRoots(realHome);
  if (within(checked.work, realHome) || secretRoots.some(root => within(checked.work, root) || within(root, checked.work))) throw new Error("agent write scope contains protected paths");
  return {
    denyReadPaths: [...secretRoots, path.join(realHome, ".claude*"),
      "**/.env", "**/.env.*", checked.sealed],
    readableRoots: [checked.data, checked.work, checked.results, checked.report],
    writableRoots: [checked.work],
    failIfUnavailable: true,
    allowUnsandboxedCommands: false,
  };
}

export interface ReexecutionOptions {
  layout: InvestigationLayout;
  home: string;
  /** Host-owned, immutable dependency roots; never generated by the worker. */
  environmentRoots: string[];
  /** Optional persistent verification of one installed, host-owned prefix. */
  environmentCache?: EnvironmentVerificationCache;
  command: string;
  args: string[];
  toolPath: string;
  timeoutMs: number;
  /** Mandatory commitment from the trusted host journal. */
  manifestSha256: string;
  maxOutputBytes?: number;
}

function forbidden(target: string, layout: InvestigationLayout, home: string, secretRoots: string[]): boolean {
  return within(layout.sealed, target) || target.split(path.sep).some(part => part === ".env" || part.startsWith(".env.")) ||
    secretRoots.some(root => within(root, target)) ||
    (within(home, target) && path.relative(home, target).split(path.sep)[0]!.startsWith(".claude"));
}

function protectedOverlap(root: string, layout: InvestigationLayout, home: string, secretRoots: string[]): boolean {
  // An ancestor grants reads of every child, so it is unsafe even if empty today.
  return forbidden(root, layout, home, secretRoots) || within(root, home) || within(root, layout.sealed) ||
    secretRoots.some(secret => within(root, secret));
}

/** Refuse secrets or escaping links inside otherwise permitted input/dependency roots.
 * Host inputs must remain immutable between preparation and completion of execution.
 */
function inspectInputs(roots: string[], layout: InvestigationLayout, home: string, secretRoots: string[], checkOwner = false): void {
  // All roots have already been canonicalized and checked with core's identity
  // helpers. Enumerated children inherit the physical spelling; resolve only
  // symlinks. Avoid O(entries × secrets × ancestors) filesystem identity lookups.
  const contains = (root: string, file: string) => file === root || file.startsWith(root + path.sep);
  const protectedRoots = [layout.sealed, ...secretRoots];
  const denied = (file: string) => protectedRoots.some(root => contains(root, file)) ||
    file.split(path.sep).some(part => part === ".env" || part.startsWith(".env.")) ||
    (contains(home, file) && path.relative(home, file).split(path.sep)[0]!.startsWith(".claude"));
  const uid = process.getuid?.();
  function visit(file: string): void {
    if (denied(file)) throw new Error(`secret or sealed input refused: ${file}`);
    const stat = lstatSync(file);
    if (checkOwner && (uid === undefined || (stat.uid !== uid && stat.uid !== 0) ||
      (!stat.isSymbolicLink() && (stat.mode & 0o022)))) throw new Error(`environment entry is not owner-controlled: ${file}`);
    if (stat.isSymbolicLink()) {
      const real = canonicalPath(file);
      if (denied(real)) throw new Error(`secret or sealed input refused: ${file}`);
      if (!roots.some(root => contains(root, real))) throw new Error(`input link escapes declared roots: ${file}`);
      // Every allowed target is itself enumerated under one of the roots. Never
      // traverse links (cycles are safe); still reject dangling and special targets.
      const target = lstatSync(real);
      if (!target.isDirectory() && (!target.isFile() || target.nlink !== 1)) throw new Error(`non-regular or hardlinked input refused: ${file}`);
    } else if (stat.isDirectory()) {
      for (const entry of readdirSync(file)) visit(path.join(file, entry));
    } else if (!stat.isFile() || stat.nlink !== 1) throw new Error(`non-regular or hardlinked input refused: ${file}`);
  }
  roots.forEach(root => {
    if (checkOwner) assertNoExtendedAcl(root, true);
    visit(root);
  });
}

/** Builds a core HostSandbox request; outputDir must be a fresh empty directory.
 * Use withReexecutionSandbox to allocate and clean that directory automatically.
 */
export function buildReexecutionRequest(input: ReexecutionOptions, outputDir: string): SandboxRequest {
  const layout = checkedLayout(input.layout);
  const home = directory(input.home);
  const secretRoots = secretReadRoots(home);
  const output = directory(outputDir);
  if (!within(layout.work, output) || output === layout.work || readdirSync(output).length !== 0) throw new Error("output must be a fresh empty directory within work");
  if (typeof input.manifestSha256 !== "string" || !/^[a-f0-9]{64}$/.test(input.manifestSha256)) throw new Error("trusted manifest commitment required");
  assertVerifiedManifest(layout.data, input.manifestSha256);
  const environmentRoots = input.environmentRoots.map(directory);
  const readableRoots = [layout.data, ...environmentRoots];
  if (readableRoots.some(root => protectedOverlap(root, layout, home, secretRoots) || within(root, layout.work) || within(layout.work, root) ||
    within(root, layout.results) || within(layout.results, root) || within(root, layout.report) || within(layout.report, root))) throw new Error("read roots overlap protected or mutable investigation paths");
  // Data and non-installed dependencies are always checked. Only a matching,
  // explicitly host-selected installed prefix may reuse persistent verification.
  const cache = input.environmentCache;
  const cachedPrefix = cache ? directory(cache.prefix) : undefined;
  if (cache && cachedPrefix && environmentRoots.includes(cachedPrefix)) {
    const state = directory(cache.stateRoot);
    if ([layout.work, ...readableRoots].some(root => within(root, state) || within(state, root))) {
      throw new Error("cache state overlaps input or worker roots");
    }
    verifyEnvironment({ ...cache, prefix: cachedPrefix, stateRoot: state }, [layout.sealed, home, ...secretRoots], prefix =>
      inspectInputs([prefix], layout, home, secretRoots, true), [layout.work, ...readableRoots]);
  }
  inspectInputs([layout.data], layout, home, secretRoots);
  inspectInputs(environmentRoots.filter(root => root !== cachedPrefix), layout, home, secretRoots, true);
  const executable = canonicalPath(input.command);
  const toolRoots = input.toolPath.split(path.delimiter);
  if (!path.isAbsolute(input.command) || toolRoots.some(root => !root || !path.isAbsolute(root))) throw new Error("command and PATH must be absolute host-owned paths");
  if (!Number.isSafeInteger(input.timeoutMs) || input.timeoutMs < 1) throw new Error("timeout must be a positive integer");
  if (input.maxOutputBytes !== undefined && (!Number.isSafeInteger(input.maxOutputBytes) || input.maxOutputBytes < 1)) throw new Error("output cap must be a positive integer");
  // HostSandbox implicitly grants command-directory, PATH and native-library reads.
  // Check both spellings; reject cheap configuration errors before native discovery.
  const checkedToolRoots = new Map<string, string>();
  function checkedToolRoot(candidate: string): string {
    const previous = checkedToolRoots.get(candidate);
    if (previous !== undefined) return previous;
    const root = directory(candidate);
    for (const spelling of new Set([candidate, root])) {
      if (protectedOverlap(spelling, layout, home, secretRoots) || within(spelling, layout.root) || within(layout.root, spelling)) throw new Error("tool roots expose investigation or secret paths");
    }
    checkedToolRoots.set(candidate, root);
    return root;
  }
  checkedToolRoot(path.dirname(executable));
  const checkedToolPath = toolRoots.map(checkedToolRoot).join(path.delimiter);
  if (process.platform === "darwin") machOLibraryRoots(executable).forEach(checkedToolRoot);
  return {
    profile: "proof", command: executable, args: [...input.args], cwd: layout.data,
    readableRoots, writableRoots: [output], artifactRoot: output,
    toolPath: checkedToolPath, allowLoopback: false, timeoutMs: input.timeoutMs,
    ...(input.maxOutputBytes === undefined ? {} : { maxOutputBytes: input.maxOutputBytes }),
  };
}

/** OS-level deny overlay, including future .env files and implicit runtime roots.
 * Core has no deny-read request field. Seatbelt supports explicit deny rules; on
 * other backends refuse rather than pretend a glob was enforced by an allowlist.
 */
function enforceDenials(invocation: SandboxInvocation, layout: InvestigationLayout, home: string): SandboxInvocation {
  if (invocation.spec === null) throw new Error(`sandbox unavailable: ${invocation.refusalReason}`);
  if (invocation.sandboxClass !== "seatbelt") throw new Error("sandbox unavailable: bio-guard requires a backend with explicit deny-read enforcement (seatbelt)");
  const args = [...invocation.spec.args];
  const policyIndex = args.indexOf("-p") + 1;
  if (policyIndex === 0 || typeof args[policyIndex] !== "string") throw new Error("sandbox policy unavailable");
  const literalRoots = [layout.sealed, ...secretReadRoots(home)];
  // Character classes avoid double escaping between JS strings and SBPL regex literals.
  // Deny .claude* globally as well, including copies made in an otherwise readable root.
  const claudePattern = "(^|/)[.]claude[^/]*(/|$)";
  const envPattern = "(^|/)[.]env([.][^/]*)?(/|$)";
  args[policyIndex] += `\n(deny file-read* ${literalRoots.map(root => `(subpath ${JSON.stringify(root)})`).join(" ")} (regex #${JSON.stringify(claudePattern)}) (regex #${JSON.stringify(envPattern)}))\n`;
  return { ...invocation, spec: { ...invocation.spec, args } };
}

/** The callback must await process completion/reaping and persist desired outputs
 * into the host evidence store before returning. Scratch is removed on all exits.
 */
export async function withReexecutionSandbox<T>(
  input: ReexecutionOptions,
  run: (invocation: SandboxInvocation & { spec: NonNullable<SandboxInvocation["spec"]> }, request: SandboxRequest) => Promise<T>,
  sandbox: HostSandbox = new HostSandbox(),
): Promise<T> {
  const layout = checkedLayout(input.layout);
  const output = mkdtempSync(path.join(layout.work, "reexecute-"));
  try {
    const request = buildReexecutionRequest(input, output);
    const invocation = enforceDenials(sandbox.prepare(request), layout, directory(input.home));
    if (!invocation.spec) throw new Error("sandbox invocation unavailable");
    return await run({ ...invocation, spec: invocation.spec }, request);
  } finally { rmSync(output, { recursive: true, force: true }); }
}
