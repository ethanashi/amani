"""V3 host-side build tool (never copied into a deliverable): writes a truth-free copy of a task's
reference.py. A static taint pass over the top-level statements of main() drops every statement
that reads `truth`, or reads a name written or mutated by an already-dropped statement (design
guards and key material that need truth, and any analysis statement that needs truth). The
output is ordinary Python produced by ast.unparse, so the sandboxed deliverable needs no dynamic
execution (V2c refuses exec/compile at freeze).

Usage: python omb_truthfree.py reference.py OUT.py
"""
from __future__ import annotations

import ast
import sys

SEED = "truth"
# In-place mutators of builtin containers and numpy arrays. Read-only calls (items, values, get...)
# never propagate taint to their receiver.
MUTATING_METHODS = frozenset({"append", "extend", "insert", "update", "pop", "popitem", "remove", "clear", "setdefault",
                              "add", "discard", "difference_update", "intersection_update", "symmetric_difference_update",
                              "sort", "reverse", "fill", "resize", "put", "itemset"})


def _names(node: ast.AST, ctx: type) -> set[str]:
    """Names in `ctx` (ast.Load / ast.Store) anywhere in node, excluding comprehension targets."""
    out: set[str] = set()
    comp_targets: set[int] = set()
    for sub in ast.walk(node):
        if isinstance(sub, ast.comprehension):
            for t in ast.walk(sub.target):
                comp_targets.add(id(t))
    for sub in ast.walk(node):
        if isinstance(sub, ast.Name) and isinstance(sub.ctx, ctx) and id(sub) not in comp_targets:
            out.add(sub.id)
    return out


def _mutated(node: ast.AST) -> set[str]:
    """Names possibly mutated in place: NAME[...] = v, NAME.attr = v (any depth) and direct calls of
    in-place mutators NAME.method(...). The caller keeps only main()'s own local variables, so module
    names such as json or np are never treated as mutated."""
    out: set[str] = set()
    for sub in ast.walk(node):
        if isinstance(sub, (ast.Subscript, ast.Attribute)) and isinstance(sub.ctx, (ast.Store, ast.Del)):
            base = sub.value
            while isinstance(base, (ast.Subscript, ast.Attribute)):
                base = base.value
            if isinstance(base, ast.Name):
                out.add(base.id)
        if (isinstance(sub, ast.Call) and isinstance(sub.func, ast.Attribute) and isinstance(sub.func.value, ast.Name)
                and sub.func.attr in MUTATING_METHODS):
            out.add(sub.func.value.id)
    return out


def taint_main(tree: ast.Module) -> tuple[ast.Module, list[int]]:
    """Drop truth-dependent top-level statements of main(); returns (tree, dropped line numbers)."""
    mains = [n for n in tree.body if isinstance(n, ast.FunctionDef) and n.name == "main"]
    if len(mains) != 1:
        raise SystemExit("reference runner: expected exactly one top-level main()")
    main = mains[0]
    local = {a.arg for a in main.args.args + main.args.kwonlyargs}
    tainted = {SEED}
    kept: list[ast.stmt] = []
    dropped: list[int] = []
    for stmt in main.body:
        reads = _names(stmt, ast.Load)
        stores = _names(stmt, ast.Store)
        writes = stores | (_mutated(stmt) & (local | stores))
        local |= stores
        if SEED in stores:
            tainted |= stores
            dropped.append(stmt.lineno)
            continue
        if reads & tainted:
            tainted |= writes
            dropped.append(stmt.lineno)
            continue
        kept.append(stmt)
    main.body = kept or [ast.Return(value=ast.Constant(value=4))]
    ast.fix_missing_locations(tree)
    return tree, dropped



def main() -> int:
    source = open(sys.argv[1]).read()
    tree, dropped = taint_main(ast.parse(source, filename=sys.argv[1]))
    note = ("# Generated by omb_truthfree.py from reference.py (V3 calibration): generator truth is unavailable;\n"
            f"# truth-dependent top-level statements of main() dropped at original lines {dropped}.\n")
    with open(sys.argv[2], "w") as fh:
        fh.write(note + ast.unparse(tree) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
