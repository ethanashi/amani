import { readFileSync, lstatSync, realpathSync } from 'node:fs';
import path from 'node:path';
import { verify } from 'node:crypto';
import { assert, canonicalSha256, safePath, sha256 } from '@omerta-bio/certificate';
/** Authenticate the supplied trusted public key independently. This checks transport
 * integrity, not scientific validity or a new execution of the certification gates. */
export function verifyBundle(root, trustedKey) {
    const payload = readFileSync(path.join(root, 'certificate.payload.json'));
    assert(verify(null, payload, trustedKey, readFileSync(path.join(root, 'certificate.sig'))), 'certificate signature invalid');
    const cert = JSON.parse(payload.toString()), manifest = JSON.parse(readFileSync(path.join(root, 'bundle-manifest.json'), 'utf8'));
    assert(canonicalSha256(manifest) === cert.bundleHash, 'bundle manifest changed');
    for (const [name, hash] of Object.entries(manifest.files)) {
        safePath(name);
        let at = root;
        for (const part of name.split('/')) {
            at = path.join(at, part);
            assert(!lstatSync(at).isSymbolicLink(), 'symlink in signed bundle');
        }
        assert(realpathSync(at).startsWith(realpathSync(root) + path.sep) && sha256(readFileSync(at)) === hash, `bundle output differs from regenerated bytes: ${name}`);
    }
}
