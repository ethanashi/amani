#!/usr/bin/env python3
"""Stage p10b-pseudorep-hidden: p10-pseudorep's synthetic iPSC-neuron RNA-seq design (12 libraries
from 4 lines x 3 differentiations), generated by p10's own generator with this card's seed, but the
sample sheet carries no line or donor column: the line structure is discoverable only from the
expression profiles (sex-chromosome genes, line-specific expression).

    stage.py --out DIR [--truth-out FILE]

Deterministic from the card seed: same seed, same bytes. Writes DIR/data/counts.tsv,
DIR/data/samples.tsv, DIR/TASK.md and DIR/manifest.json. Generator truth (the sample -> line map) is
written only when --truth-out is given, and only inside the grading root (never into DIR).
"""
from __future__ import annotations

import importlib.util
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1] / "lib"))

from biotasks import staging  # noqa: E402

_spec = importlib.util.spec_from_file_location("p10_stage", HERE.parent / "p10-pseudorep" / "stage.py")
p10 = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(p10)

HIDDEN = ("line_id", "donor_sex")
KEEP = [i for i, h in enumerate(p10.HEADER) if h not in HIDDEN]
HEADER = [p10.HEADER[i] for i in KEEP]


def main() -> int:
    a = staging.stage_args()
    card = json.loads((HERE / "card.json").read_text())
    data = staging.prepare_out(a.out)
    truth_out = staging.guard_truth(a.truth_out, a.out)
    rows, genes, counts, truth = p10.generate(card["seed"])
    staging.write_tsv(data / "samples.tsv", HEADER, ([r[i] for i in KEEP] for r in rows))
    sids = [r[0] for r in rows]
    staging.write_tsv(data / "counts.tsv", ["gene"] + sids,
                      ([g] + [str(int(v)) for v in counts[i]] for i, g in enumerate(genes)))
    staging.write_truth(truth_out, {**truth, "task": card["id"]})
    staging.finalize(a.out, HERE, card["id"], card["seed"])
    return 0


if __name__ == "__main__":
    sys.exit(main())
