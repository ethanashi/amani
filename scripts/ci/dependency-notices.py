#!/usr/bin/env python3
"""Generate release notices from installed npm metadata and frozen pixi inventories.
Never reads host benchmark data, keys or user configuration.
"""
from pathlib import Path
import csv
import hashlib
import json
import os
import subprocess
import tomllib

ROOT = Path(__file__).resolve().parents[2]

def command(args):
    return subprocess.check_output(args, cwd=ROOT, text=True)

def digest(file):
    return hashlib.sha256(file.read_bytes()).hexdigest()

def row(values):
    return '| ' + ' | '.join(str(v).replace('|', '\\|').replace('\n', ' ') for v in values) + ' |'

def table(headings, rows):
    return [row(headings), row(['---'] * len(headings)), *[row(r) for r in rows], '']

def generate():
    npm = json.loads(command(['pnpm', 'licenses', 'list', '--json']))
    records = []
    for license, packages in npm.items():
        for p in packages:
            records.append((p['name'], ', '.join(p['versions']), license, p.get('homepage', '')))
    records.sort()
    out = ['# Third-party licenses', '',
           'Generated by `python3 scripts/ci/dependency-notices.py` from the installed npm graph,',
           'the frozen pixi locks (all declared platforms), installed R DESCRIPTION metadata and the',
           'figure-reference Python license inventory. Versions and license expressions are upstream metadata.',
           'Dependency environments and npm caches are excluded from the publish export; consumers provision',
           'them separately. Third-party files keep their original grants; the root license does not relicense them.', '',
           '## Boundaries', '',
           '- The TypeScript engine runs on Node; its external runtime graph is dagre/graphlib (MIT).',
           '- Studio uses the npm and Rust components recorded below and in its retained notices.',
           '- Python/R analysis, reference checks, format codecs, Pandoc and Tectonic run as separate programs.',
           '  GPL/LGPL packages in those environments are not imported or linked into the Node engine or Studio.',
           '  No Python-to-Node FFI, embedded libR or libgsl is permitted. Interpreters exchange files and process output.',
           '- The Python figure reference environment is explicitly excluded from the product renderer:',
           '  its strict native-runtime gate rejects it. Product figures are TypeScript.',
           '- Apache verifier/format production imports are restricted by `pnpm lint`; the linked-code',
           '  gate in `scripts/ci/licences.mjs` rejects GPL-family third-party npm, vendored and Rust runtime code.',
           '- The AGPL engine itself is the first-party grant, not a third-party GPL dependency.', '',
           '## npm: installed production and development dependencies', '',
           f'{len(records)} name/version/license records. Development tools are included; platform-optional packages',
           'not installed on this host are not presented as installed dependencies.', '']
    out += table(['Component', 'Installed version(s)', 'License', 'Upstream'], records)
    out += ['## pixi / conda: frozen package inventories', '',
            'Each table comes from `pixi list --json --platform PLATFORM --manifest-path MANIFEST`.',
            'This reads the pinned solver result, including native libraries, Python packages and R packages.',
            'Rows include build identifiers because a version may have distinct licensed builds.', '']
    pins = [ROOT / 'pnpm-lock.yaml']
    for file in sorted(ROOT.glob('packages/**/pixi.toml')):
        if '.pixi' in file.parts: continue
        lock = file.with_name('pixi.lock')
        if not lock.is_file(): raise RuntimeError('missing frozen lock: ' + str(file.relative_to(ROOT)))
        pins += [file, lock]
        manifest = tomllib.loads(file.read_text())
        platforms = manifest.get('workspace', manifest.get('project', {}))['platforms']
        for platform in platforms:
            data = json.loads(command(['pixi', 'list', '--manifest-path', str(file), '--platform', platform, '--json']))
            out += [f'### `{file.relative_to(ROOT)}` — {platform}', '', f'{len(data)} locked packages; environment is external to the Node process.', '']
            out += table(['Component', 'Version', 'Build', 'License'],
                         [(p['name'], p['version'], p.get('build', ''), p.get('license') or 'NOT DECLARED upstream') for p in sorted(data, key=lambda p:p['name'])])
    out += ['## R: installed reference interpreter libraries', '',
            'Read from the cloned baseline R library DESCRIPTION files; includes the bundled R base/recommended',
            'packages. GPL R and GPL packages execute only in the separate reference process.', '']
    library = ROOT / 'packages/bio-baseline/.pixi/envs/default/lib/R/library'
    rrows = []
    for file in sorted(library.glob('*/DESCRIPTION')):
        fields = {}; key = None
        for line in file.read_text().splitlines():
            if line[:1].isspace() and key: fields[key] += ' ' + line.strip()
            elif ':' in line:
                key, value = line.split(':', 1); fields[key] = value.strip()
        rrows.append((fields['Package'], fields['Version'], fields.get('License', 'NOT DECLARED upstream')))
    if not rrows: raise RuntimeError('installed R library inventory missing')
    out += table(['Package', 'Version', 'License'], rrows)
    out += ['## Python figure-reference wheels (separate, non-product environment)', '',
            'Pinned versions are cross-checked against the existing metadata inventory in',
            '`packages/omb-figures/LICENSES/python-dependencies.json`. Wheels and their native runtimes',
            'are not redistributed with the product. See `packages/omb-figures/python/README.md`.', '']
    req = ROOT/'packages/omb-figures/python/requirements.lock'
    metadata = ROOT/'packages/omb-figures/LICENSES/python-dependencies.json'
    pins += [req, metadata]
    data = json.loads(metadata.read_text())
    wheelrows=[]
    for line in req.read_text().splitlines():
        if not line.strip() or line.startswith('#'): continue
        name, version = line.split('==')
        found = next((p for p in data if p['name'].lower()==name.lower() and p['version']==version), None)
        if found is None: raise RuntimeError('missing Python reference metadata: ' + name)
        wheelrows.append((name,version,found['license']))
    out += table(['Distribution', 'Version', 'License'], wheelrows)
    out += ['## Rust, vendored code, fonts and data', '',
            '- Studio: `apps/amani-studio/THIRD-PARTY-LICENSES.txt`, `Node-LICENSE.txt` and',
            '  `public/THIRD-PARTY-LICENSES.txt` retain full component attribution. The linked runtime',
            '  is checked against exact `Cargo.lock` resolutions by the CI license stage.',
            '- Figures: `packages/omb-figures/LICENSES/` records dependency and asset hashes and grants.',
            '- Packaging: `packages/omb-package/vendor/NOTICE.md`, the GUST font license and Tectonic license.',
            '- Report: `packages/omb-report/vendor/UNICODE-LICENSE.txt` and `data-to-paper-LICENSE`.',
            '- `third_party/LICENSE.openpyxl` and `third_party/codex-sandboxing/LICENSE` retain upstream grants.',
            '- Other `vendor/`, `LICENSES/` and component notices remain beside the relevant sources.',
            '- Retired replication data references, fetchers and example papers retain their source-specific',
            '  attribution and access terms in `examples/replications/*/README.md` and data-build records.',
            '- The excluded race baseline requirements and vendored reference agent are development-only;',
            '  they are not engine or Studio dependencies and are not provisioned by the product.', '',
            '## Inventory input hashes', '']
    out += table(['Input', 'SHA-256'], [(str(p.relative_to(ROOT)), digest(p)) for p in pins])
    (ROOT/'docs/third-party-licenses.md').write_text('\n'.join(out))
    notice = '''Amani
Copyright (c) 2026 Ethan Ashihundu

The engine and documentation are AGPL-3.0-only except where a component
states a different license. The independent verifier and certificate format
(packages/omb-verifier and packages/omb-certificate) are Apache-2.0.
Amani Studio retains its MIT grant. Each component includes its license.

Third-party components retain their original copyrights and licenses.
This NOTICE records attribution and does not change those license terms.
The complete versioned inventory, scope, and lock hashes are recorded in
docs/third-party-licenses.md; regenerate with scripts/ci/dependency-notices.py.

Bundled-source and binary attribution:
- dagre and graphlib: Dagre contributors, MIT; installed npm licenses apply.
- Studio: React, Tauri, PDF.js, Lucide and their transitive components;
  see apps/amani-studio/THIRD-PARTY-LICENSES.txt and Node-LICENSE.txt.
- OpenAI codex-sandboxing: third_party/codex-sandboxing/LICENSE.
- openpyxl: third_party/LICENSE.openpyxl.
- colorspacious: packages/omb-figures/vendor/colorspacious-LICENSE.txt.
- Unicode data: packages/omb-report/vendor/UNICODE-LICENSE.txt.
- data-to-paper materials: packages/omb-report/vendor/data-to-paper-LICENSE.
- Latin Modern fonts: packages/omb-package/vendor/fonts/GUST-FONT-LICENSE.txt.
- Tectonic: packages/omb-package/vendor/tex/TECTONIC-LICENSE.txt.
- Packaging assets and upstream templates: packages/omb-package/vendor/NOTICE.md
  and component LICENSES manifests, which retain individual grants.

R, GPL/LGPL analysis libraries and Pandoc are separate executables in pinned
reference or packaging environments. None is linked into the Node engine or
Studio. Reference Python wheels are not bundled product renderers.
Environments, caches and node_modules are excluded from the public snapshot.
If distributing binaries or environment packages, retain all corresponding
license files and meet each component's source and notice obligations.
'''
    (ROOT/'NOTICE').write_text(notice)
    print(f'Generated NOTICE and third-party inventory: {len(records)} npm records, {len(rrows)} R packages, {len(wheelrows)} figure-reference wheels.')

if __name__ == '__main__': generate()
